// Builds the public spell catalogue.
//   node scripts/catalogue/build-spells.mjs --from <workDir> <book…>   cleaned batches → data JSON
//   node scripts/catalogue/build-spells.mjs                             data JSON → src/catalogue/spells.ts
// The data JSON (`scripts/catalogue/data/spells-<book>.json`) holds facts, names and our own
// summaries — never the books' text, which stays in the private work files. A spell reprinted in a
// newer book of the same rule set keeps only the newest entry.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = new URL('.', import.meta.url);
const dataDir = new URL('data/', here);
const RULES = { phb14: '2014', xge: '2014', tce: '2014', phb24: '2024', frhof: '2024' };
/** Newest last: a reprint keeps the entry of the book furthest down. */
const ORDER = ['phb14', 'xge', 'tce', 'phb24', 'frhof'];
const FACTS = [
	'name',
	'nameDe',
	'level',
	'school',
	'casting',
	'range',
	'components',
	'material',
	'duration',
	'concentration',
	'ritual',
	'classes',
	'damage',
	'save',
	'attack',
	'summary',
];

export const slug = (name) =>
	name
		.normalize('NFD')
		.replace(/\p{M}/gu, '')
		.toLowerCase()
		.replace(/[’']/g, '')
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-|-$/g, '');

function fromWork(workDir, books) {
	const norm = join(workDir, 'norm');
	// The SRD's spell names, from the plugin's SRD data.
	const srdSource = readFileSync(new URL('../../src/spells/srd-spells.ts', here), 'utf8');
	const fold = (name) => name.replace(/\\'/g, "'").toLowerCase().replace(/’/g, "'");
	// SRD English name → its index, and index → the plugin's German name (src/spells/de.ts).
	const srdIndex = new Map(
		[...srdSource.matchAll(/^ {4}index: '([^']+)',\r?\n {4}name: (['"])(.+)\2,$/gm)].map(
			(m) => [fold(m[3]), m[1]],
		),
	);
	const srd = new Set(srdIndex.keys());
	const deSource = readFileSync(new URL('../../src/spells/de.ts', here), 'utf8');
	const deNames = new Map(
		[...deSource.matchAll(/^ {2}'?([a-z0-9-]+)'?: (['"])(.+)\2,$/gm)].map((m) => [m[1], m[3]]),
	);
	/** A newer version of an SRD spell keeps the SRD's German name. */
	const nameDe = (e) => deNames.get(srdIndex.get(fold(e.name)) ?? '') ?? e.nameDe;
	for (const book of books) {
		const files = readdirSync(norm).filter(
			(f) => f.startsWith(`${book}-`) && /-\d+\.json$/.test(f),
		);
		const entries = files
			.flatMap((f) => JSON.parse(readFileSync(join(norm, f), 'utf8')))
			.filter((e) => e.srd == null && e.note !== 'not a spell')
			// The cleaners missed a few SRD names; a 2014 book never repeats an SRD spell.
			.filter((e) => RULES[book] !== '2014' || !srd.has(fold(e.name)));
		const spells = entries
			.map((e) =>
				Object.fromEntries([
					['index', `${book}/${slug(e.name)}`],
					...FACTS.map((k) => [k, k === 'nameDe' ? nameDe(e) : e[k]]),
				]),
			)
			.sort((a, b) => a.index.localeCompare(b.index));
		const seen = new Set();
		const unique = spells.filter((s) => !seen.has(s.index) && seen.add(s.index));
		writeFileSync(
			new URL(`spells-${book}.json`, dataDir),
			`${JSON.stringify(unique, null, 1)}\n`,
		);
		console.log(
			`${book}: ${unique.length} spells (${spells.length - unique.length} duplicates dropped)`,
		);
	}
}

function toSource() {
	const books = ORDER.filter((b) => readdirSync(dataDir).includes(`spells-${b}.json`));
	const newest = new Map();
	for (const book of books) {
		for (const s of JSON.parse(readFileSync(new URL(`spells-${book}.json`, dataDir), 'utf8'))) {
			newest.set(`${RULES[book]}:${slug(s.name)}`, {
				...s,
				rules: RULES[book],
				source: book,
			});
		}
	}
	const all = [...newest.values()].map((s) => ({ ...s, text: '', higher: '' }));
	all.sort((a, b) => a.index.localeCompare(b.index));
	const out = `// The spell catalogue: facts, names and summaries in our own words for the spells of the books in
// \`src/catalogue/books.ts\` that are not in the SRD (see NOTICE.md). Generated by
// scripts/catalogue/build-spells.mjs from scripts/catalogue/data/. Do not edit by hand.

import type { SrdSpell } from '../spells/model';

export const CATALOGUE_SPELLS: readonly SrdSpell[] = ${JSON.stringify(all, null, 2)};
`;
	writeFileSync(new URL('../../src/catalogue/spells.ts', here), out);
	console.log(`src/catalogue/spells.ts: ${all.length} spells from ${books.join(', ')}`);
}

const args = process.argv.slice(2);
if (args[0] === '--from') fromWork(args[1], args.slice(2));
else toSource();
