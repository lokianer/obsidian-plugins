import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

// Obsidian loads one stylesheet from the plugin's folder: styles/index.css and the files it imports,
// bundled in their order into styles.css (not minified, so it stays readable in the vault).
const styles = await esbuild.context({
	banner: {
		css: '/* Built from styles/ by esbuild: edit those files, not this one. */',
	},
	entryPoints: ['styles/index.css'],
	bundle: true,
	logLevel: 'info',
	outfile: 'styles.css',
});

if (prod) {
	await context.rebuild();
	await styles.rebuild();
	process.exit(0);
} else {
	await Promise.all([context.watch(), styles.watch()]);
}
